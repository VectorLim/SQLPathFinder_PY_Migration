class hmData:
    def __init__( self, rawDF, boundsDF ):
        self._rawDF = rawDF
        self._boundsDF = boundsDF
        self._aqn = re.compile( '.*-J[0-9]+$' )

    def _getBounds( self ):
        # Extract cluster boundaries for specified variable into a list
        bounds = [float(x) for x in self._boundsDF[ self._boundsDF[ 'C0' ]==self._rawVar]['bounds'].iloc[-1].tolist()]

        # This adjusts the boundary when the min and lowest bound are the same. In the
        # case of two clusters, without this correction the heat map effectively shows
        # only one row/column for the affected variable.
        if self._min == bounds[0]:
            sortVar = sorted( self._data )
            nextVal = [ x for x in sortVar if x > bounds[0]]
            bounds[0] = (bounds[0] + nextVal[0]) / 2
            logging.warning( f'{self._var} lowest bound==min value={self._min}, adjusting to {bounds[0]}' )

        return [self._min] + bounds + [self._max] 

    def _setVar( self, aqVarName ):
        self._var = aqVarName

        # Make sure variable is an autoQuant numeric
        if not self._aqn.match( aqVarName ):
            raise ValueError( f'plotHeatMap|bad variable <{aqVarName}> - must provide autoQuant numeric' )

        # Strip -Jn from autoQuant column name
        self._rawVar = re.sub( '-J[0-9]+$', '', aqVarName )
        
        # Extract unquantized variables for histograms
        try:
            self._data = self._rawDF[ self._rawVar ]
        except KeyError as err:
            logging.error( f'plotHeatMap|bad variable name: {err}' )
            return None

        self._min = self._data.min()
        self._max = self._data.max()

        self._lines = self._getBounds()

        # Range to get matrix dims from number of lines. _lines includes boundaries at
        # edges so subtract one to get the number of bins
        self._range = range( len( self._lines ) - 1 )

